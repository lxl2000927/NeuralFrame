'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const entries = JSON.parse(fs.readFileSync(path.join(root, 'overlay/zh-cn-extra.json'), 'utf8'));
// Match complete conversion specifications, including * width/precision and length.
const specs = s => [...s.matchAll(/%(?:%|[-+ #0]*(?:\*|\d+)?(?:\.(?:\*|\d*))?(?:hh|ll|I32|I64|[hlLjzt])?[diuoxXfFeEgGaAcspn])/g)].map(m=>m[0]).filter(s=>s!=='%%');
const quote = s => '"' + [...Buffer.from(s)].map(b=>'\\x'+b.toString(16).padStart(2,'0')).join('') + '"';
const rows=[];
for (const [en,zh] of Object.entries(entries)) {
  const a=specs(en),b=specs(zh);
  if(a.some(s=>s.endsWith('n')) || JSON.stringify(a)!==JSON.stringify(b)) throw new Error(`Unsafe format: ${en} -> ${zh}: ${a} / ${b}`);
  if(en.includes('\0')) continue; // Combo2 translates each zero-separated item, never the entire array.
  rows.push(`  {${quote(en)}, ${quote(zh)}, ${a.length ? 'true':'false'}},`);
}
const out='// SPDX-License-Identifier: MIT\n// Generated by scripts/generate-zh-extra.js. Edit zh-cn-extra.json.\nnamespace zh_extra {\nstruct Entry {const char *en; const char *zh; bool has_printf_specs;};\ninline constexpr Entry entries[] = {\n'+rows.join('\n')+'\n};\n}\n';
fs.writeFileSync(path.join(root,'overlay/zh-cn-extra.hpp'),out);
console.log(`Validated and generated ${rows.length} Chinese entries`);
module.exports={specs};
